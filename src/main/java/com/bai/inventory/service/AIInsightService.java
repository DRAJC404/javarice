public class AIInsightService {

    public record InsightResult(List<AiInsight> insights, boolean isAiGenerated, String statusNote) {}

    private final AiInsightDao aiInsightDao;
    private final ProductDao productDao;
    private final HttpClient httpClient;
    private final ObjectMapper objectMapper;

    public AIInsightService() {
        this(new AiInsightDao(), new ProductDao());
    }

    public AIInsightService(AiInsightDao aiInsightDao, ProductDao productDao) {
        this.aiInsightDao = aiInsightDao;
        this.productDao = productDao;
        this.httpClient = HttpClient.newBuilder()
                .connectTimeout(Duration.ofSeconds(20))
                .build();
        this.objectMapper = new ObjectMapper();
    }

    public InsightResult getInsights(User user) {
        int orgId = resolveOrganizationId(user);

        // 1. Check existing active insights in database cache first
        List<AiInsight> cached = aiInsightDao.findActiveInsights(5, orgId);
        if (!cached.isEmpty()) {
            return new InsightResult(cached, true, "Active cached insights");
        }

        // 2. Minimum movement days check: skip AI call if fewer than 7 days of movement data
        int distinctDays = aiInsightDao.getDistinctMovementDaysCount(orgId);
        if (distinctDays < 7) {
            List<AiInsight> fallback = generateRuleBasedInsights(orgId);
            return new InsightResult(
                    fallback,
                    false,
                    "AI requires at least 7 days of stock movements (recorded " + distinctDays + " days). Showing rule-based insights."
            );
        }

        // 3. API key configuration check
        if (!EnvConfig.hasApiKey()) {
            List<AiInsight> fallback = generateRuleBasedInsights(orgId);
            return new InsightResult(
                    fallback,
                    false,
                    "AI model not configured (set AI_API_KEY in .env). Showing rule-based insights."
            );
        }

        // 4. Daily call limit check: limit to 20 AI calls per organization per day
        boolean allowed = aiInsightDao.recordAiCallAndCheckLimit(orgId, 20);
        if (!allowed) {
            List<AiInsight> fallback = generateRuleBasedInsights(orgId);
            return new InsightResult(
                    fallback,
                    false,
                    "Daily AI limit reached (20 calls/day). Showing rule-based insights."
            );
        }

        // 5. Gather anonymous, aggregated inventory data only (no emails, names, or IDs)
        String anonData = aiInsightDao.getAggregatedAnonymousInventoryData(orgId);

        // 6. Call LLM with 20-second timeout and 1 retry
        try {
            List<AiInsight> aiInsights = requestInsightsWithRetry(anonData);
            if (!aiInsights.isEmpty()) {
                aiInsightDao.cacheAiInsights(orgId, aiInsights);
                return new InsightResult(aiInsights, true, "Generated by " + EnvConfig.getModel());
            }
        } catch (Exception ex) {
            System.err.println("[AIInsightService] LLM request failed, falling back to rule-based: " + ex.getMessage());
        }

        // Fallback if model parsing or execution returned empty
        List<AiInsight> fallback = generateRuleBasedInsights(orgId);
        return new InsightResult(fallback, false, "AI service temporarily unavailable. Showing rule-based insights.");
    }

    public String askBai(String question, User user) {
        if (user == null || user.getOrganizationId() <= 0) {
            return "Authentication error: Verified tenant organization is required.";
        }
        int orgId = user.getOrganizationId();

        if (question == null || question.trim().isEmpty()) {
            return "Please ask a specific inventory question.";
        }
        String sanitizedQ = question.trim();
        if (sanitizedQ.length() > 200) {
            return "Question is too long (maximum 200 characters). Please rephrase concisely.";
        }

        if (!EnvConfig.hasApiKey()) {
            String anon = aiInsightDao.getAggregatedAnonymousInventoryData(orgId);
            return "bAI Assistant (Rule-based fallback, AI_API_KEY not configured in .env):\n\n" +
                   "Here is your current anonymous tenant summary:\n" + anon;
        }

        boolean allowed = aiInsightDao.recordAiCallAndCheckLimit(orgId, 20);
        if (!allowed) {
            return "Daily AI question limit reached (20 calls/day). Please try again tomorrow.";
        }

        String anonData = aiInsightDao.getAggregatedAnonymousInventoryData(orgId);
        String prompt =
                "You are bAI Assistant, an inventory copilot. Answer the following question about retail inventory " +
                "using ONLY the provided anonymous tenant metrics. Keep the response concise, factual, under 300 words, " +
                "and formatted in plain text (no markdown headings, no HTML).\n\n" +
                "Tenant Inventory Metrics:\n" + anonData + "\n\n" +
                "Question: " + sanitizedQ;

        try {
            return callLlmRaw(prompt);
        } catch (Exception ex) {
            return "bAI Assistant was unable to process your question: " + ex.getMessage();
        }
    }

    private List<AiInsight> requestInsightsWithRetry(String anonymousData) throws Exception {
        Exception lastException = null;
        for (int attempt = 1; attempt <= 2; attempt++) {
            try {
                String prompt = buildInsightPrompt(anonymousData);
                String rawResponse = callLlmRaw(prompt);
                List<AiInsight> parsed = parseInsightJson(rawResponse);
                if (!parsed.isEmpty()) {
                    return parsed;
                }
            } catch (Exception ex) {
                lastException = ex;
                if (attempt == 1) {
                    try { Thread.sleep(500); } catch (InterruptedException ignored) {}
                }
            }
        }
        throw lastException != null ? lastException : new IOException("Failed to obtain AI insights after 2 attempts.");
    }

    private String buildInsightPrompt(String anonymousData) {
        return "You are an expert retail inventory analytics AI for the bAI platform.\n" +
               "Analyze the following ANONYMOUS, aggregated inventory velocity and health data:\n\n" +
               anonymousData + "\n\n" +
               "Generate 3 distinct, high-impact inventory insights in strict JSON format conforming to this schema:\n" +
               "[\n" +
               "  {\n" +
               "    \"category\": \"FAST_MOVING\" | \"DEMAND_FORECAST\" | \"LOW_STOCK\" | \"OVERSTOCK\" | \"SLOW_MOVING\" | \"EXPIRY_RISK\" | \"ANOMALY\" | \"RESTOCK_RECOMMENDATION\",\n" +
               "    \"title\": \"Clear concise headline under 100 characters\",\n" +
               "    \"description\": \"Actionable plain-text explanation under 250 characters\",\n" +
               "    \"severity\": \"INFO\" | \"WARNING\" | \"OPPORTUNITY\",\n" +
               "    \"metricValue\": \"Key figure under 30 characters (e.g. '1.4 days left', '4 Low-Stock')\",\n" +
               "    \"actionLabel\": \"Button label under 40 characters (e.g. 'Quick Restock')\",\n" +
               "    \"actionCommand\": \"OPEN_RESTOCK_MODAL\" | \"NAVIGATE_INVENTORY\" | \"EXPORT_REORDER_PDF\"\n" +
               "  }\n" +
               "]\n\n" +
               "CRITICAL: Return ONLY valid JSON array with no markdown backticks, no markdown code block, and no commentary.";
    }

    private String callLlmRaw(String prompt) throws Exception {
        String apiKey = EnvConfig.getApiKey();
        String model = EnvConfig.getModel();
        String baseUrl = EnvConfig.getBaseUrl();

        if (baseUrl != null || (apiKey != null && apiKey.startsWith("gsk_"))) {
            // OpenAI / Groq compatible chat completions
            String endpoint = baseUrl != null ? baseUrl : "https://api.groq.com/openai/v1";
            if (!endpoint.endsWith("/chat/completions")) {
                if (endpoint.endsWith("/")) endpoint += "chat/completions";
                else endpoint += "/chat/completions";
            }

            Map<String, Object> bodyMap = new HashMap<>();
            bodyMap.put("model", model);
            List<Map<String, String>> messages = new ArrayList<>();
            messages.add(Map.of("role", "system", "content", "You are an inventory assistant that outputs plain text or strict JSON as requested."));
            messages.add(Map.of("role", "user", "content", prompt));
            bodyMap.put("messages", messages);
            bodyMap.put("temperature", 0.2);

            String requestBody = objectMapper.writeValueAsString(bodyMap);
            HttpRequest request = HttpRequest.newBuilder()
                    .uri(URI.create(endpoint))
                    .header("Content-Type", "application/json")
                    .header("Authorization", "Bearer " + apiKey)
                    .timeout(Duration.ofSeconds(20))
                    .POST(HttpRequest.BodyPublishers.ofString(requestBody))
                    .build();

            HttpResponse<String> response = httpClient.send(request, HttpResponse.BodyHandlers.ofString());
            if (response.statusCode() >= 200 && response.statusCode() < 300) {
                JsonNode root = objectMapper.readTree(response.body());
                JsonNode choices = root.path("choices");
                if (choices.isArray() && !choices.isEmpty()) {
                    return choices.get(0).path("message").path("content").asText();
                }
            }
            throw new IOException("Chat completions API error (" + response.statusCode() + "): " + response.body());
        } else {
            // Google Gemini API generateContent endpoint
            String endpoint = "https://generativelanguage.googleapis.com/v1beta/models/" + model + ":generateContent?key=" + apiKey;
            Map<String, Object> bodyMap = new HashMap<>();
            Map<String, Object> part = Map.of("text", prompt);
            Map<String, Object> content = Map.of("parts", List.of(part));
            bodyMap.put("contents", List.of(content));

            String requestBody = objectMapper.writeValueAsString(bodyMap);
            HttpRequest request = HttpRequest.newBuilder()
                    .uri(URI.create(endpoint))
                    .header("Content-Type", "application/json")
                    .timeout(Duration.ofSeconds(20))
                    .POST(HttpRequest.BodyPublishers.ofString(requestBody))
                    .build();

            HttpResponse<String> response = httpClient.send(request, HttpResponse.BodyHandlers.ofString());
            if (response.statusCode() >= 200 && response.statusCode() < 300) {
                JsonNode root = objectMapper.readTree(response.body());
                JsonNode candidates = root.path("candidates");
                if (candidates.isArray() && !candidates.isEmpty()) {
                    JsonNode parts = candidates.get(0).path("content").path("parts");
                    if (parts.isArray() && !parts.isEmpty()) {
                        return parts.get(0).path("text").asText();
                    }
                }
            }
            throw new IOException("Gemini API error (" + response.statusCode() + "): " + response.body());
        }
    }

    private List<AiInsight> parseInsightJson(String rawText) {
        List<AiInsight> list = new ArrayList<>();
        if (rawText == null || rawText.isBlank()) return list;

        String cleaned = rawText.trim();
        // Strip markdown backticks ```json ... ``` if model wrapped it
        if (cleaned.startsWith("```")) {
            int firstNewline = cleaned.indexOf('\n');
            int lastBackticks = cleaned.lastIndexOf("```");
            if (firstNewline != -1 && lastBackticks > firstNewline) {
                cleaned = cleaned.substring(firstNewline + 1, lastBackticks).trim();
            }
        }

        try {
            JsonNode root = objectMapper.readTree(cleaned);
            JsonNode arrayNode = root.isArray() ? root : root.path("insights");
            if (arrayNode.isArray()) {
                int idCounter = 1;
                for (JsonNode item : arrayNode) {
                    String cat = item.path("category").asText("FAST_MOVING");
                    String title = item.path("title").asText("Inventory Update");
                    String desc = item.path("description").asText("");
                    String sev = item.path("severity").asText("INFO");
                    String metric = item.path("metricValue").asText("");
                    if (metric.isEmpty()) metric = item.path("metric_value").asText("");
                    String actionLabel = item.path("actionLabel").asText("View Details");
                    if (actionLabel.isEmpty()) actionLabel = item.path("action_label").asText("View Details");
                    String actionCmd = item.path("actionCommand").asText("NAVIGATE_INVENTORY");
                    if (actionCmd.isEmpty()) actionCmd = item.path("action_command").asText("NAVIGATE_INVENTORY");

                    list.add(new AiInsight(
                            idCounter++,
                            cat,
                            title,
                            desc,
                            sev,
                            metric,
                            actionLabel,
                            actionCmd,
                            false,
                            null
                    ));
                }
            }
        } catch (Exception e) {
            System.err.println("[AIInsightService] Error parsing LLM JSON: " + e.getMessage() + " | Raw: " + rawText);
        }

        return list;
    }

    public List<AiInsight> generateRuleBasedInsights(int organizationId) {
        List<AiInsight> fallback = new ArrayList<>();
        List<Product> products = productDao.findAll(organizationId);

        long lowStockCount = products.stream().filter(Product::isLowStock).count();
        long outOfStockCount = products.stream().filter(Product::isOutOfStock).count();

        if (outOfStockCount > 0) {
            fallback.add(new AiInsight(
                    1,
                    "LOW_STOCK",
                    outOfStockCount + " product" + (outOfStockCount > 1 ? "s" : "") + " currently out of stock",
                    "Immediate restock required to prevent lost sales and fulfillment delays.",
                    "WARNING",
                    outOfStockCount + " Out-of-Stock",
                    "Review Stockouts",
                    "NAVIGATE_INVENTORY",
                    false,
                    null
            ));
        }

        if (lowStockCount > 0) {
            fallback.add(new AiInsight(
                    2,
                    "RESTOCK_RECOMMENDATION",
                    lowStockCount + " product" + (lowStockCount > 1 ? "s" : "") + " below reorder threshold",
                    "Recommended purchase order replenishment batch to maintain healthy safety stock.",
                    "WARNING",
                    lowStockCount + " Critical",
                    "Quick Restock",
                    "OPEN_RESTOCK_MODAL",
                    false,
                    null
            ));
        }

        fallback.add(new AiInsight(
                3,
                "DEMAND_FORECAST",
                "Weekly inventory velocity baseline calculated",
                "Stock turnover trends reflect consistent demand patterns across core categories.",
                "INFO",
                "Healthy",
                "View Analytics",
                "NAVIGATE_ANALYTICS",
                false,
                null
        ));

        return fallback;
    }

    private int resolveOrganizationId(User user) {
        if (user != null && user.getOrganizationId() > 0) {
            return user.getOrganizationId();
        }
        User current = com.bai.inventory.service.AuthService.getCurrentUser();
        return (current != null && current.getOrganizationId() > 0) ? current.getOrganizationId() : 1;
    }
}
